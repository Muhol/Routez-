// ============================================================
// Routez Admin — Database Types (mirrors Supabase schema)
// ============================================================

export type Sacco = {
  id: string;
  name: string;
  logo_url: string | null;
  contact_phone: string | null;
  rating: number;
  created_at: string;
};

export type Route = {
  id: string;
  route_number: string;
  origin_name: string;
  destination_name: string;
  created_at: string;
};

export type Stage = {
  id: string;
  name: string;
  area: string;
  latitude: number;
  longitude: number;
  // `location` is a generated PostGIS column — never insert/update directly
  created_at: string;
};

export type SaccoRoute = {
  id: string;
  sacco_id: string;
  route_id: string;
  fare_offpeak: number;
  fare_peak: number;
  typical_duration_mins: number;
  fleet_type: string;
  is_express: boolean;
  is_active: boolean;
  path?: string | null;
  created_at: string;
  // joined relations
  saccos?: Sacco;
  routes?: Route;
};

export type SaccoRouteStage = {
  id: string;
  sacco_route_id: string;
  stage_id: string;
  stop_order: number;
  distance_from_start_km: number;
  eta_from_start_mins: number;
  fare_offpeak?: number;
  fare_peak?: number;
  fare_offpeak_min?: number;
  fare_offpeak_max?: number;
  fare_peak_min?: number;
  fare_peak_max?: number;
  // joined
  stages?: Stage;
  sacco_routes?: SaccoRoute;
};

export type ServiceAlert = {
  id: string;
  sacco_route_id: string;
  title: string;
  message: string;
  severity: 'info' | 'warning' | 'critical';
  starts_at: string;
  ends_at: string | null;
  created_at: string;
  sacco_routes?: SaccoRoute;
};

export type SaccoRouteFare = {
  id: string;
  sacco_route_id: string;
  from_stage_id: string;
  to_stage_id: string;
  fare_offpeak: number;
  fare_peak: number;
  created_at: string;
  from_stage?: Stage;
  to_stage?: Stage;
  sacco_routes?: SaccoRoute;
};

// ─── Insert types (id & created_at omitted — generated by DB) ─────────────────

export type SaccoInsert = Omit<Sacco, 'id' | 'created_at'>;
export type RouteInsert = Omit<Route, 'id' | 'created_at'>;
export type StageInsert = Omit<Stage, 'id' | 'created_at'>;
export type SaccoRouteInsert = Omit<SaccoRoute, 'id' | 'created_at' | 'saccos' | 'routes'>;
export type SaccoRouteStageInsert = Omit<SaccoRouteStage, 'id' | 'stages' | 'sacco_routes'>;
export type ServiceAlertInsert = Omit<ServiceAlert, 'id' | 'created_at' | 'sacco_routes'>;
export type SaccoRouteFareInsert = Omit<SaccoRouteFare, 'id' | 'created_at' | 'from_stage' | 'to_stage' | 'sacco_routes'>;

// ─── Dashboard stats ──────────────────────────────────────────────────────────

export type DashboardStats = {
  totalRoutes: number;
  totalStages: number;
  totalSaccos: number;
  totalSaccoRoutes: number;
  totalRouteStages: number;
  totalFares: number;
  totalAlerts: number;
};

// ─── Import types ─────────────────────────────────────────────────────────────

export type ImportStatus =
  | 'idle' | 'parsing' | 'mapping' | 'validating'
  | 'previewing' | 'resolving' | 'importing' | 'complete' | 'error';

export type ValidationSeverity = 'ok' | 'warning' | 'error';

export type RowIssue = {
  field: string;
  message: string;
  severity: ValidationSeverity;
};

export type RowValidation = {
  rowIndex: number;
  status: ValidationSeverity;
  issues: RowIssue[];
};

export type ImportSession = {
  id: string;
  category: ImportCategory;
  fileName: string;
  startedAt: string;
  totalRows: number;
  validRows: number;
  warningRows: number;
  errorRows: number;
  createdCount: number;
  updatedCount: number;
  skippedCount: number;
  failedCount: number;
  status: 'pending' | 'in_progress' | 'complete' | 'failed';
};

export type ImportCategory =
  | 'routes'
  | 'stages'
  | 'saccos'
  | 'sacco_routes'
  | 'route_sequences'
  | 'fares'
  | 'service_alerts'
  | 'complete_route';
